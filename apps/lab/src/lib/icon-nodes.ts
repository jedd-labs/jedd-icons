import rawIconNodes from "generated/icon-nodes.json";
import type { Variant } from "@/lib/icons";
import type { IconNodeChild } from "@/lib/svg-path";
import type {
  Issue,
  MarginReport,
} from "../../../../tools/build-icons/check-rules";

interface IconNodeEntry {
  /** What `icons:check` reports for this icon, sidecar `.json` included. */
  issues: Issue[];
  /** How far the geometry crosses the 1px margin; null if it can't be read. */
  margin: MarginReport | null;
  /** Parsed sidecar `.json`, or null when it's missing or isn't valid JSON. */
  meta: unknown;
  /** Source geometry: one element per part, as authored. */
  node: IconNodeChild[];
  pascalName: string;
  /** What the packages ship: stroke icons merged into as few paths as possible. */
  shipped: IconNodeChild[];
  variant: string;
}

// Keyed by kebab source name (e.g. "alert-circle") → variant → geometry.
// Generated by `pnpm gen-icon-nodes` from icons/**/*.svg.
// JSON.parse widens the tuple geometry to `(string | {...})[][]`, which doesn't
// structurally match the IconNodeChild tuple, so cast through `unknown`. The
// generator guarantees the shape.
const iconNodes = rawIconNodes as unknown as Record<
  string,
  Partial<Record<Variant, IconNodeEntry>>
>;

/** Every kebab icon name that has geometry, sorted. */
export const ICON_NODE_NAMES = Object.keys(iconNodes).sort((a, b) =>
  a.localeCompare(b)
);

/** Variants an icon's geometry exists in, in canonical order. */
export function getVariantsWithGeometry(name: string): Variant[] {
  const entry = iconNodes[name];
  if (!entry) {
    return [];
  }
  return (["stroke", "fill"] as const).filter((v) => v in entry);
}

/** Raw parsed geometry for an icon+variant, or null when absent. */
export function getIconNode(
  name: string,
  variant: Variant
): IconNodeChild[] | null {
  return iconNodes[name]?.[variant]?.node ?? null;
}

/** The geometry the packages ship for an icon+variant, or null when absent. */
export function getShippedIconNode(
  name: string,
  variant: Variant
): IconNodeChild[] | null {
  return iconNodes[name]?.[variant]?.shipped ?? null;
}

/** Parsed sidecar metadata for an icon+variant, or null when absent. */
export function getIconMeta(name: string, variant: Variant): unknown {
  return iconNodes[name]?.[variant]?.meta ?? null;
}

/** What `icons:check` reports for an icon+variant. */
export function getIconIssues(name: string, variant: Variant): Issue[] {
  return iconNodes[name]?.[variant]?.issues ?? [];
}

/** The icon+variant's margin measurement, or null when absent. */
export function getIconMargin(
  name: string,
  variant: Variant
): MarginReport | null {
  return iconNodes[name]?.[variant]?.margin ?? null;
}

/** PascalCase component name for a kebab icon name + variant, or null. */
export function getPascalName(name: string, variant?: Variant): string | null {
  const entry = iconNodes[name];
  if (!entry) {
    return null;
  }
  const chosen = variant ? entry[variant] : (entry.stroke ?? entry.fill);
  return chosen?.pascalName ?? null;
}
